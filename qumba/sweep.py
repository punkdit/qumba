def build(n, checks, logicals):
    xstab = [idxs for (c,idxs) in checks if c=="X"]
    mx = len(xstab)
    Hx = numpy.zeros((mx, n), dtype=int)
    for i,idxs in enumerate(xstab):
        Hx[i,idxs] = 1
    Hx = Matrix(Hx)
    Hx = Hx.linear_independent()
    #print(Hx)

    zstab = [idxs for (c,idxs) in checks if c=="Z"]
    mz = len(zstab)
    Hz = numpy.zeros((mz, n), dtype=int)
    for i,idxs in enumerate(zstab):
        Hz[i,idxs] = 1
    Hz = Matrix(Hz)
    Hz = Hz.linear_independent()
    #print(Hz)

    assert len(logicals)%2 == 0
    k = len(logicals)//2
    #Lx = numpy.zeros((k, n))
    #Lz = numpy.zeros((k, n))
    Lx = []
    Lz = []
    for c,idx in logicals:
        op = [0]*n
        for i in idx:
            op[i] = 1
        if c=="X":
            Lx.append(op)
        elif c=="Z":
            Lz.append(op)
        else:
            assert 0
    Lx = Matrix(Lx)
    Lz = Matrix(Lz)

    if argv.verbose:
        print(checks)
        print(logicals)
        print("Hx:")
        print(Hx, Hx.shape)
        print("Hz:")
        print(Hz, Hz.shape)
        print("Lx:")
        print(Lx, Lx.shape)
        print("Lz:")
        print(Lz, Lz.shape)

    code = CSSCode(Hx=Hx, Hz=Hz, Lx=Lx, Lz=Lz)
    code.bz_distance()
    return code


